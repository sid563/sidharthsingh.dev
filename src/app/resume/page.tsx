import type { Metadata } from "next";
import fs from "node:fs";
import path from "node:path";
import { DownloadIcon, ExternalLinkIcon } from "lucide-react";
import { buttonVariants } from "@/components/ui/button";
import { Container } from "@/components/container";
import { PageHeader } from "@/components/page-header";
import { PrintButton } from "@/components/resume/print-button";
import {
  ContactLine,
  Credentials,
  Education,
  Experience,
  SelectedProjects,
  Skills,
  Summary,
} from "@/components/resume/resume-sections";
import { resume } from "@/data/resume";
import { site } from "@/data/site";
import { documents } from "@/data/links";
import { getProject } from "@/lib/content";
import "./print.css";

export const metadata: Metadata = {
  title: "Resume",
  description: `${resume.name}: ${resume.headline}.`,
};

/** Generated by `pnpm resume:pdf` and committed; the button only shows when the file exists. */
const generatedPdf = "/resume/sidharth-singh-resume.pdf";
const hasGeneratedPdf = fs.existsSync(path.join(process.cwd(), "public", generatedPdf));

export default function ResumePage() {
  const projects = resume.projectSlugs
    .map((slug) => getProject(slug))
    .filter((project) => project !== null);

  return (
    <Container className="pb-8">
      <PageHeader eyebrow="Resume" title={resume.name} description={resume.headline} className="pb-6">
        <PrintButton />
        {hasGeneratedPdf ? (
          <a
            href={generatedPdf}
            download="Sidharth-Singh-Resume.pdf"
            className={buttonVariants({ variant: "outline", className: "print:hidden" })}
          >
            Download PDF
            <DownloadIcon />
          </a>
        ) : null}
        {documents.resume.url ? (
          <a
            href={documents.resume.path}
            target="_blank"
            rel="noreferrer"
            className={buttonVariants({ variant: "outline", className: "print:hidden" })}
          >
            Original PDF
            <ExternalLinkIcon />
          </a>
        ) : null}
        <a
          href={site.linkedin}
          target="_blank"
          rel="noreferrer"
          className={buttonVariants({ variant: "outline", className: "print:hidden" })}
        >
          LinkedIn
          <ExternalLinkIcon />
        </a>
      </PageHeader>

      <div className="mb-8">
        <ContactLine />
      </div>

      <Summary />
      <Experience />
      <Education />
      <Skills />
      <Credentials />
      <SelectedProjects projects={projects} />
    </Container>
  );
}
